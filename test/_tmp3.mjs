import puppeteer from 'puppeteer';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch();
const p = await b.newPage();
await p.setViewport({ width: 1280, height: 900 });
p.on('pageerror', (e) => console.log('PAGEERR', e.message));
await p.goto(`http://localhost:8101/localkit/en/edit-pdf/`, { waitUntil: 'networkidle0' });
await (await p.$('#pe-pick input[type=file]')).uploadFile('test/fixtures/a.pdf');
await p.waitForFunction(() => document.querySelectorAll('#pe-pages canvas').length >= 1, { timeout: 30000 });
await sleep(800);
await p.evaluate(() => window.scrollBy(0, document.querySelector('.epage').getBoundingClientRect().top - 240));
await sleep(300);
const box = await (await p.$('.epage')).boundingBox();
const s = box.width / 595;
const at = (x, y) => [box.x + x * s, box.y + y * s];
await p.click('#pe-tools [data-tool="text"]');
await p.select('#pe-font', 'serif');
await p.click('#pe-bold');
console.log(await p.evaluate(() => window.scrollY + ' ' + JSON.stringify(document.querySelector('.epage').getBoundingClientRect())));
await p.mouse.click(...at(100, 560));
await sleep(300);
console.log(await p.evaluate(() => document.activeElement.tagName + ' ' + JSON.stringify(window.__pe.anns)));
await b.close();
