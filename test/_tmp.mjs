import puppeteer from 'puppeteer';
const lang = process.argv[2] || 'en', w = Number(process.argv[3] || 1280), fx = process.argv[4] || 'edit-text.pdf';
const b = await puppeteer.launch();
const p = await b.newPage();
await p.setViewport({ width: w, height: w < 600 ? 800 : 900, deviceScaleFactor: 1 });
p.on('pageerror', (e) => console.log('PAGEERR', e.message));
await p.goto(`http://localhost:8101/localkit/${lang}/edit-pdf/`, { waitUntil: 'networkidle0' });
await (await p.$('#pe-pick input[type=file]')).uploadFile(`test/fixtures/${fx}`);
await p.waitForFunction(() => document.querySelectorAll('#pe-pages canvas').length >= 1, { timeout: 30000 });
await new Promise((r) => setTimeout(r, 1000));
await p.evaluate(() => window.scrollBy(0, document.querySelector('.pe-top').getBoundingClientRect().top - 60));
await new Promise((r) => setTimeout(r, 300));
await p.screenshot({ path: `test/out/shot-${lang}-${w}.png` });
console.log(await p.evaluate(() => document.documentElement.scrollWidth + ' ' + document.querySelector('.pe-top').offsetHeight));
await b.close();
