import puppeteer from 'puppeteer';
import fs from 'node:fs';
import * as pdfjs from 'pdfjs-dist/legacy/build/pdf.mjs';
const lang = process.argv[2] || 'en';
const b = await puppeteer.launch();
const p = await b.newPage();
await p.setViewport({ width: 1280, height: 900 });
p.on('pageerror', (e) => console.log('PAGEERR', e.message));
p.on('console', (m) => { if (['error', 'warning'].includes(m.type()) || m.text().startsWith('SCRUB')) console.log('CONSOLE', m.type(), m.text().slice(0, 300)); });
const cdp = await p.createCDPSession();
import path from 'node:path';
await cdp.send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: path.resolve('test/out'), eventsEnabled: true });
let dl = null; cdp.on('Browser.downloadWillBegin', (e) => { dl = e.suggestedFilename; });
await p.goto(`http://localhost:8101/localkit/${lang}/edit-pdf/`, { waitUntil: 'networkidle0' });
await (await p.$('#pe-pick input[type=file]')).uploadFile('test/fixtures/edit-text.pdf');
await p.waitForFunction(() => document.querySelectorAll('#pe-pages canvas').length >= 1, { timeout: 30000 });
await new Promise((r) => setTimeout(r, 800));
await p.evaluate(() => window.scrollBy(0, document.querySelector('.epage').getBoundingClientRect().top - 240));
const box = await (await p.$('.epage')).boundingBox();
const s = box.width / 595;
const click = async (x, y) => { await p.mouse.click(box.x + x * s, box.y + (842 - y) * s); await new Promise((r) => setTimeout(r, 300)); };
const sel = async () => { await p.keyboard.down('Control'); await p.keyboard.press('a'); await p.keyboard.up('Control'); };
await click(100, 764); await sel(); await p.keyboard.type('Receipt Number 99'); 
await click(100, 694); await p.screenshot({ path: 'test/out/shot-edit1.png' });
await sel(); await p.keyboard.type('Customer: Beta GmbH');
await click(100, 644); await sel(); await p.keyboard.type('合同金额：乙方收款');
await p.mouse.click(box.x + 300 * s, box.y + 500 * s); await new Promise((r) => setTimeout(r, 300));
await p.screenshot({ path: 'test/out/shot-edit2.png' });
console.log(JSON.stringify(await p.evaluate(() => window.__pe.anns.map((a) => ({ t: a.text, f: a.font, sz: a.size, c: a.color, cv: a.cover?.color, k: a.kill })))));
await p.click('#pe-save');
await p.waitForSelector('#pe-result .result', { timeout: 30000 });
await new Promise((r) => setTimeout(r, 800));
console.log('downloaded', dl);
const doc = await pdfjs.getDocument({ data: new Uint8Array(fs.readFileSync('test/out/' + dl)), standardFontDataUrl: './node_modules/pdfjs-dist/standard_fonts/' }).promise;
const tc = await (await doc.getPage(1)).getTextContent();
console.log(JSON.stringify(tc.items.map((i) => i.str).filter(Boolean)));
await b.close();
